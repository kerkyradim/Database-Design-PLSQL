--A PROCEDURE TO UPDATE THE RETURN DATE IN A STILL BORROWED BOOK
CREATE OR REPLACE PROCEDURE UPDATERETURNDATE(BOOK_ISBN IN BOOKS.ISBN%TYPE,RETURN_DATE IN BORROWS.RETURNDATE%TYPE)
AS
BEGIN 
 DECLARE
        BOOK_AVAIL BORROWS.AVALIABILLITY%TYPE;
        CURSOR book IS 
            SELECT bo.AVALIABILLITY
            FROM BOOKS b JOIN BORROWS bo 
            ON b.ISBN=bo.BOOKISBN
            WHERE b.ISBN=BOOK_ISBN;
 BEGIN           
    OPEN book;
    LOOP
        FETCH book INTO BOOK_AVAIL;
        EXIT WHEN book%NotFound;
    END LOOP; 
    
    IF(BOOK_AVAIL=1) THEN
        DBMS_OUTPUT.PUT_LINE('Book is still avaliable');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Book is still borrowed');
        UPDATE BORROWS
        SET RETURNDATE=RETURN_DATE WHERE BOOKISBN=BOOK_ISBN;
        
        UPDATE BORROWS
        SET AVALIABILLITY=1 WHERE BOOKISBN=BOOK_ISBN;
        
        UPDATE BORROWS
        SET MEMBERID=NULL WHERE BOOKISBN=BOOK_ISBN;
        
        UPDATE BORROWS
        SET DAYSBORROWED=(SELECT TO_DATE(BORROWS.RETURNDATE,'DD-MM-YYYY')- 
        TO_DATE (BORROWS.BORROWDATE,'DD-MM-YYYY')
        FROM DUAL);
    END IF;
    END;
END;
