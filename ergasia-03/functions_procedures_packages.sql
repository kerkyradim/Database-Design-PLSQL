--A PROCEDURE TO BORROW A BOOK TO A MEMBER 
CREATE OR REPLACE PROCEDURE BORROWBOOK(M_NAME IN MEMBERS.NAME%TYPE,BOOK_TITLE IN BOOKS.TITLE%TYPE)
AS
 BEGIN
    DECLARE 
    BOOK_ISBN BOOKS.ISBN%TYPE;
    M_ID MEMBERS.ID%TYPE;
    BOOK_AVAIL BORROWS.AVALIABILLITY%TYPE;
    CURSOR book IS 
                SELECT b.ISBN,bo.AVALIABILLITY
                FROM BOOKS b JOIN BORROWS bo 
                ON b.ISBN=bo.BOOKISBN
                WHERE b.TITLE=BOOK_TITLE;
    BEGIN
        DBMS_OUTPUT.PUT_LINE('MEMBER:'||M_NAME||' WANTS TO BORROW BOOK WITH TITLE:'||BOOK_TITLE);
        OPEN book;
        LOOP
            FETCH book INTO BOOK_ISBN,BOOK_AVAIL;
            EXIT WHEN book%NotFound;
        END LOOP;
        SELECT ID INTO M_ID FROM MEMBERS WHERE NAME=M_NAME;
        --DBMS_OUTPUT.PUT_LINE(BOOK_AVAIL ||  BOOK_ISBN);
            IF (BOOK_AVAIL=1) THEN
                UPDATE BORROWS
                SET MEMBERID=M_ID WHERE BOOKISBN=BOOK_ISBN;
                
                UPDATE BORROWS 
                SET AVALIABILLITY=0 WHERE BOOKISBN=BOOK_ISBN;
                
                UPDATE BORROWS 
                SET BORROWDATE=sysdate WHERE BOOKISBN=BOOK_ISBN;
                
                UPDATE BORROWS 
                SET RETURNDATE=NULL WHERE BOOKISBN=BOOK_ISBN;
                
                UPDATE BORROWS 
                SET DAYSBORROWED=NULL WHERE BOOKISBN=BOOK_ISBN;
                
                DBMS_OUTPUT.PUT_LINE('DONE!');
                
            ELSE
                DBMS_OUTPUT.PUT_LINE('The book is not avaliable');
            END IF;
        
        CLOSE book;
        END;
 END;
 /

