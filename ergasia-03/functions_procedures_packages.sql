--A PROCEDURE THAT RETURNS A BOOK BY TITLE
CREATE OR REPLACE PROCEDURE BOOKINFO (BOOK_TITLE  IN BOOKS.TITLE%TYPE) AS
BEGIN
  DECLARE BOOK_ISBN BOOKS.ISBN%TYPE;
          BOOK_CATEGORY BOOKS.CATEGORY%TYPE;
          BOOK_WRITER BOOKS.WRITER%TYPE;
          CURSOR book IS 
            SELECT ISBN,WRITER,CATEGORY FROM BOOKS  WHERE TITLE=BOOK_TITLE;
  BEGIN
  OPEN book;
  LOOP
    FETCH book INTO BOOK_ISBN,BOOK_WRITER,BOOK_CATEGORY;
    EXIT WHEN book%NotFound; 
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('ISBN:'|| BOOK_ISBN);
  DBMS_OUTPUT.PUT_LINE('TITLE:'|| BOOK_TITLE);
  DBMS_OUTPUT.PUT_LINE('WRITER:'|| BOOK_WRITER);
  DBMS_OUTPUT.PUT_LINE('CATEGORY:'|| BOOK_CATEGORY);
 CLOSE book;

  
    END;
END;
