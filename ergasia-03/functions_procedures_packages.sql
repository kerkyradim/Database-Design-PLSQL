--A PROCEDURE TO RETURN A BOOK WHICH IS IN BORROW MODE
CREATE OR REPLACE PROCEDURE RETURNBORROWEDBOOK(BOOK_TITLE IN BOOKS.TITLE%TYPE)
AS
BEGIN
 DECLARE
        BOOK_ISBN BOOKS.ISBN%TYPE;
        BOOK_AVAIL BORROWS.AVALIABILLITY%TYPE;
        CURSOR book IS 
                SELECT b.ISBN,bo.AVALIABILLITY
                FROM BOOKS b JOIN BORROWS bo 
                ON b.ISBN=bo.BOOKISBN
                WHERE b.TITLE=BOOK_TITLE;

BEGIN
    OPEN book;
        LOOP
            FETCH book INTO BOOK_ISBN,BOOK_AVAIL;
            EXIT WHEN book%NotFound;
        END LOOP;
        --DBMS_OUTPUT.PUT_LINE(BOOK_ISBN  || BOOK_AVAIL);
        IF (BOOK_AVAIL=0) THEN
            DBMS_OUTPUT.PUT_LINE('Book must be returned');
            UPDATE BORROWS
            SET AVALIABILLITY=1 WHERE BOOKISBN=BOOK_ISBN;
            
            UPDATE BORROWS
            SET RETURNDATE=SYSDATE WHERE BOOKISBN=BOOK_ISBN;
            
            UPDATE BORROWS
            SET MEMBERID=null WHERE BOOKISBN=BOOK_ISBN;
            
            UPDATE BORROWS 
            SET DAYSBORROWED=(SELECT TO_DATE(BORROWS.RETURNDATE,'DD-MM-YYYY')- 
            TO_DATE (BORROWS.BORROWDATE,'DD-MM-YYYY')
            FROM DUAL);
            
        ELSE
            DBMS_OUTPUT.PUT_LINE('Book is avaliable');
        END IF;
    END;
END;
